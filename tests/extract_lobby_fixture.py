"""Extract two isolated routines for LobbyNativeAbiTests (never launch the game).

Generated bytes are private local test data; do not commit or distribute them.
Dependencies: pefile, capstone. Usage: script.py decrypted.exe fixture.bin
"""
import pathlib
import sys
import capstone
import pefile

pe = pefile.PE(sys.argv[1], fast_load=True)
decoder = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
blocks = []
for rva, size, cleanup in [(0xF0BD0, 0x7A, '8'), (0x2B030, 0xEC, '0x10')]:
    code = pe.get_data(rva, size)
    instructions = list(decoder.disasm(code, rva))
    assert sum(i.size for i in instructions) == size
    assert all(i.op_str == cleanup for i in instructions if i.mnemonic == 'ret')
    blocks.append(code)
pathlib.Path(sys.argv[2]).write_bytes(b''.join(blocks))
print('Local unlock/roster-insert fixture written (no game launched).')
